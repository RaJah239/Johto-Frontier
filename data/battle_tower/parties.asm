MACRO bt_mon
	db \1 ; species
	db \2 ; item
	db \3, \4, \5, \6 ; moves
ENDM

MACRO assert_bt_pool
	assert (\2 - \1) % BATTLETOWER_MON_STRUCT_LENGTH == 0, "\1 length must use compact BT mon records"
	assert (\2 - \1) / BATTLETOWER_MON_STRUCT_LENGTH <= $ff, "\1 must fit in a one-byte compact BT pool count"
ENDM

